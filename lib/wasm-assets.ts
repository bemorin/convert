/**
 * Reassemble independent, same-origin chunks into a Blob URL. This keeps every
 * deployed asset below Cloudflare's 25 MiB limit without a remote CDN or R2.
 * Chunks can be independently cached by the browser between visits.
 */
type WasmPart = { file: string; size: number; sha256: string };
type WasmManifest = { schema: 1; totalBytes: number; parts: WasmPart[] };

export function parseWasmManifest(input: unknown): WasmManifest {
  if (!input || typeof input !== "object") throw new Error("Invalid FFmpeg WASM manifest.");
  const data = input as Record<string, unknown>;
  if (data.schema !== 1 || !Array.isArray(data.parts) ||
      data.parts.length < 1 || data.parts.length > 16 ||
      !Number.isSafeInteger(data.totalBytes) || (data.totalBytes as number) <= 0) {
    throw new Error("Invalid FFmpeg WASM manifest.");
  }
  let total = 0;
  const parts: WasmPart[] = [];
  for (const value of data.parts) {
    if (!value || typeof value !== "object") throw new Error("Invalid FFmpeg WASM part.");
    const part = value as Record<string, unknown>;
    if (typeof part.file !== "string" || !/^ffmpeg-core\.wasm\.part-\d{2,3}$/.test(part.file) ||
        typeof part.size !== "number" || !Number.isSafeInteger(part.size) ||
        part.size < 1 || part.size > 20 * 1024 * 1024 ||
        typeof part.sha256 !== "string" || !/^[a-f0-9]{64}$/.test(part.sha256)) {
      throw new Error("Invalid FFmpeg WASM part.");
    }
    total += part.size;
    parts.push({ file: part.file, size: part.size, sha256: part.sha256 });
  }
  if (total !== data.totalBytes ||
      new Set(parts.map(part => part.file)).size !== parts.length) {
    throw new Error("Incomplete FFmpeg WASM manifest.");
  }
  return { schema: 1, totalBytes: total, parts };
}

export async function loadWasmObjectURL(manifestURL: string, baseURL: string): Promise<string> {
  const manifestResponse = await fetch(manifestURL);
  if (!manifestResponse.ok) {
    throw new Error(`Missing FFmpeg asset ${new URL(manifestURL).pathname} (HTTP ${manifestResponse.status}).`);
  }
  const manifest = parseWasmManifest(await manifestResponse.json());
  // All URLs are generated by our own build script and restricted by parser.
  // Fetching parts in parallel reduces first-conversion latency.
  const parts = await Promise.all(manifest.parts.map(async ({ file, size, sha256 }) => {
    const response = await fetch(new URL(file, baseURL));
    if (!response.ok) throw new Error(`Missing FFmpeg asset ${file} (HTTP ${response.status}).`);
    const bytes = await response.arrayBuffer();
    if (bytes.byteLength !== size) throw new Error(`Corrupt FFmpeg WASM asset: ${file}.`);
    const digest = await crypto.subtle.digest("SHA-256", bytes);
    const hex = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, "0")).join("");
    if (hex !== sha256) throw new Error(`FFmpeg WASM checksum mismatch: ${file}.`);
    return bytes;
  }));
  // Blob can share underlying ArrayBuffers, avoiding a redundant Uint8Array copy.
  return URL.createObjectURL(new Blob(parts, { type: "application/wasm" }));
}
